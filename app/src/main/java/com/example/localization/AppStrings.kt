    fun get(lang: String, key: String): String =
        (if (lang == "en") en[key] else ar[key]) ?: ar[key] ?: key

    fun dayNames(lang: String): List<String> =
        if (lang == "en") listOf("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")
        else listOf("أحد", "اثنين", "ثلاثاء", "أربعاء", "خميس", "جمعة", "سبت")

    fun formatTime(hm: String, lang: String): String {
        if (hm.isBlank() || !hm.contains(":")) return ""
        val parts = hm.split(":")
        val h24 = parts[0].toIntOrNull() ?: return hm
        val m = parts[1].toIntOrNull() ?: 0
        val suffix = if (lang == "ar") {
            if (h24 >= 12) "م" else "ص"
        } else {
            if (h24 >= 12) "PM" else "AM"
        }
        val h12 = if (h24 % 12 == 0) 12 else h24 % 12
        return "$h12:${m.toString().padStart(2, '0')} $suffix"
    }

    fun formatSeconds(sec: Int): String =
        "${sec / 60}:${(sec % 60).toString().padStart(2, '0')}"

    fun todayStr(): String = LocalDate.now().format(DateTimeFormatter.ISO_LOCAL_DATE)

    fun addDaysStr(days: Long): String =
        LocalDate.now().plusDays(days).format(DateTimeFormatter.ISO_LOCAL_DATE)

    fun nextWeekDay(days: List<Long>, fromDateStr: String): String {
        if (days.isEmpty()) return fromDateStr
        val start = runCatching { LocalDate.parse(fromDateStr) }.getOrElse { LocalDate.now() }
        for (i in 0 until 7) {
            val candidate = start.plusDays(i.toLong())
            // Map java.time.DayOfWeek (MON=1..SUN=7) to JS getDay() (SUN=0..SAT=6)
            val jsDay = (candidate.dayOfWeek.value % 7).toLong()
            if (days.contains(jsDay)) {
                return candidate.format(DateTimeFormatter.ISO_LOCAL_DATE)
            }
        }
        return fromDateStr
    }
